-- ============================================
-- Realtime (idempotent: skip tables already in the publication)
-- ============================================
do $$
begin
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'classes') then
    alter publication supabase_realtime add table public.classes;
  end if;
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'profiles') then
    alter publication supabase_realtime add table public.profiles;
  end if;
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'announcements') then
    alter publication supabase_realtime add table public.announcements;
  end if;
end$$;

-- ============================================
-- RPC: Archive registrations of a month
-- ============================================
create or replace function public.archive_registrations(p_start date, p_end date)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_count integer;
begin
  if not public.is_admin() then
    raise exception 'Permission denied: admin only';
  end if;
  insert into public.archived_registrations (class_name, date, meal_type, count, registered_by, registered_by_id, updated_at)
  select class_name, date, meal_type, count, registered_by, registered_by_id, updated_at
  from public.registrations
  where date >= p_start and date <= p_end;

  get diagnostics v_count = row_count;

  delete from public.registrations where date >= p_start and date <= p_end;

  return v_count;
end;
$$;

-- ============================================
-- RPC: Delete an auth user + profile (by admin)
-- ============================================
create or replace function public.delete_user(p_user_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then
    raise exception 'Permission denied: admin only';
  end if;
  delete from auth.users where id = p_user_id;
end;
$$;

-- ============================================
-- RPC: Classes already registered for a date (any authenticated user)
-- Returns only class names, so teachers can see the summary count
-- without being able to read other classes' meal counts.
-- ============================================
create or replace function public.get_registered_classes(p_date date)
returns table(class_name text)
language sql
security definer
set search_path = public
stable
as $$
  select r.class_name
  from public.registrations r
  where r.date = p_date
    and r.count > 0
    and r.meal_type in ('Bữa trưa (trẻ)', 'Bữa trưa (GV)')
  group by r.class_name;
$$;

grant execute on function public.get_registered_classes(date) to authenticated;
