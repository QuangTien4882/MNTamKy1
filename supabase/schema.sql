-- Prevent non-admins from changing permission-relevant profile fields.
-- Users may update their own display_name (e.g. via signUp) but never role,
-- assigned_class or email.
create or replace function public.guard_profile_update()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if (new.id <> auth.uid()) and (not public.is_admin()) then
    raise exception 'Permission denied: cannot edit this profile';
  end if;
  if not public.is_admin() and (
    new.role is distinct from old.role
    or new.assigned_class is distinct from old.assigned_class
    or new.email is distinct from old.email
  ) then
    raise exception 'Permission denied: cannot change role, class or email';
  end if;
  return new;
end;
$$;

drop trigger if exists on_profiles_update_guard on public.profiles;
create trigger on_profiles_update_guard
  before update on public.profiles
  for each row execute procedure public.guard_profile_update();

-- Prevent non-admin/BGH users from editing announcements title/content.
-- Non-privileged users may only mark announcements as read (append own id).
create or replace function public.guard_announcement_update()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if public.is_admin() or public.is_bgh() then
    return new;
  end if;
  -- Only allow appending the current user's id to read_by; block all else.
  if (
    new.title is distinct from old.title
    or new.content is distinct from old.content
    or new.created_by is distinct from old.created_by
    or new.created_by_id is distinct from old.created_by_id
  ) then
    raise exception 'Permission denied: cannot edit announcement';
  end if;
  if new.read_by is distinct from old.read_by then
    if array_length(new.read_by, 1) > array_length(old.read_by, 1) then
      new.read_by := (select array_agg(distinct x order by x) from unnest(new.read_by) x);
    else
      raise exception 'Permission denied: cannot remove read status';
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists on_announcements_update_guard on public.announcements;
create trigger on_announcements_update_guard
  before update on public.announcements
  for each row execute procedure public.guard_announcement_update();

