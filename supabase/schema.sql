-- Read access is role-scoped so teachers only see data of their own class,
-- while Admin / BGH / KT&CD see everything relevant to their screens.
drop policy if exists "allow_read_classes" on public.classes;
create policy "allow_read_classes" on public.classes for select using (auth.role() = 'authenticated');
drop policy if exists "allow_read_profiles" on public.profiles;
create policy "allow_read_profiles" on public.profiles for select using (public.is_admin() or public.is_bgh());
drop policy if exists "allow_read_own_profile" on public.profiles;
create policy "allow_read_own_profile" on public.profiles for select using (auth.uid() = id);
drop policy if exists "allow_read_registrations" on public.registrations;
create policy "allow_read_registrations" on public.registrations for select using (
  public.is_admin() or public.is_bgh() or public.is_kt_cd()
  or (
    public.current_user_role() = 'Giáo viên'
    and public.current_user_assigned_class() = class_name
  )
);
drop policy if exists "allow_read_announcements" on public.announcements;
create policy "allow_read_announcements" on public.announcements for select using (auth.role() = 'authenticated');
drop policy if exists "allow_read_audit_logs" on public.audit_logs;
create policy "allow_read_audit_logs" on public.audit_logs for select using (public.is_admin());
drop policy if exists "allow_read_archived" on public.archived_registrations;
create policy "allow_read_archived" on public.archived_registrations for select using (public.is_admin());

-- Writes: enforced by role (business rules live in the application AND here).

-- ---- classes: Admin only ----
drop policy if exists "allow_write_classes" on public.classes;
drop policy if exists "admin_write_classes" on public.classes;
create policy "admin_write_classes" on public.classes
  for all using (public.is_admin()) with check (public.is_admin());

-- ---- profiles: update own (guarded) or admin; delete admin only ----
drop policy if exists "allow_write_profiles" on public.profiles;
drop policy if exists "user_update_own_profile" on public.profiles;
create policy "user_update_own_profile" on public.profiles
  for update using (auth.uid() = id or public.is_admin())
  with check (auth.uid() = id or public.is_admin());
drop policy if exists "admin_delete_profiles" on public.profiles;
create policy "admin_delete_profiles" on public.profiles
  for delete using (public.is_admin());

-- ---- registrations: Admin / KT&CD any class, GV only own class ----
drop policy if exists "allow_write_registrations" on public.registrations;
drop policy if exists "admin_write_registrations" on public.registrations;
create policy "admin_write_registrations" on public.registrations
  for all using (public.is_admin()) with check (public.is_admin());
drop policy if exists "kt_write_registrations" on public.registrations;
create policy "kt_write_registrations" on public.registrations
  for all using (public.is_kt_cd()) with check (public.is_kt_cd());
drop policy if exists "gv_write_own_class_registrations" on public.registrations;
create policy "gv_write_own_class_registrations" on public.registrations
  for all using (
    public.current_user_role() = 'Giáo viên'
    and public.current_user_assigned_class() = class_name
  )
  with check (
    public.current_user_role() = 'Giáo viên'
    and public.current_user_assigned_class() = class_name
  );

-- ---- announcements: Admin / BGH manage; others read only (mark-as-read via trigger) ----
drop policy if exists "allow_write_announcements" on public.announcements;
drop policy if exists "admin_bgh_write_announcements" on public.announcements;
create policy "admin_bgh_write_announcements" on public.announcements
  for all using (public.is_admin() or public.is_bgh())
  with check (public.is_admin() or public.is_bgh());
drop policy if exists "authenticated_read_announcement" on public.announcements;
create policy "authenticated_read_announcement" on public.announcements
  for update using (auth.role() = 'authenticated')
  with check (auth.role() = 'authenticated');

-- ---- audit_logs: any authenticated may insert; Admin deletes ----
drop policy if exists "allow_write_audit_logs" on public.audit_logs;
drop policy if exists "authenticated_insert_audit_logs" on public.audit_logs;
create policy "authenticated_insert_audit_logs" on public.audit_logs
  for insert with check (auth.role() = 'authenticated');
drop policy if exists "admin_delete_audit_logs" on public.audit_logs;
create policy "admin_delete_audit_logs" on public.audit_logs
  for delete using (public.is_admin());

-- ---- archived_registrations: Admin only ----
drop policy if exists "allow_write_archived" on public.archived_registrations;
drop policy if exists "admin_write_archived" on public.archived_registrations;
create policy "admin_write_archived" on public.archived_registrations
  for all using (public.is_admin()) with check (public.is_admin());

