-- Note: auth.users is created automatically by Supabase Auth.
-- profiles references auth.users(id) and holds the app user details.

create table if not exists public.classes (
  id bigint generated by default as identity primary key,
  name text not null unique,
  student_count integer not null default 0,
  updated_at timestamptz not null default now()
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  display_name text not null default '',
  role text not null default 'Chưa duyệt',
  assigned_class text,
  updated_at timestamptz not null default now()
);

-- Fix tables created by the OLD schema (create table if not exists does NOT
-- update the default of an existing table).
alter table public.profiles alter column role set default 'Chưa duyệt';

-- Sĩ số: suất ăn của trẻ (bữa trưa & bữa mai) không được vượt quá sĩ số lớp.
-- Chạy cho cả INSERT (đăng ký trực tiếp) lẫn UPDATE (kể cả qua RPC ghi/lock).
create or replace function public.enforce_registration_capacity()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_student_count integer;
begin
  if new.meal_type in ('Bữa trưa (trẻ)', 'Bữa mai (trẻ)') then
    select coalesce(student_count, 0) into v_student_count
    from public.classes
    where name = new.class_name;
    if new.count > v_student_count then
      raise exception 'Số lượng suất ăn của trẻ vượt quá sĩ số lớp.' using errcode = 'P0001';
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists enforce_registration_capacity_trigger on public.registrations;
create trigger enforce_registration_capacity_trigger
before insert or update on public.registrations
for each row
execute function public.enforce_registration_capacity();

-- Auto-create a profile whenever an auth user is created.
-- Idempotent: if a profile already exists (duplicate/retry), it just syncs the
-- email + display name without touching role/class (which are set by admins).
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
insert into public.profiles (id, email, display_name)
  values (
    new.id,
    new.email,
    coalesce(new.raw_user_meta_data ->> 'display_name', split_part(coalesce(new.email, ''), '@', 1))
  )
  on conflict (id) do update
  set email = excluded.email,
      display_name = case
        when coalesce(excluded.display_name, '') = '' then public.profiles.display_name
        else excluded.display_name
      end;
  return new;
end;
$$;

-- Keep the profile email in sync when the user changes their email in Auth.
create or replace function public.sync_auth_user_profile()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.profiles
  set email = new.email,
      updated_at = now()
  where id = new.id
    and email is distinct from new.email;
  return new;
end;
$$;

drop trigger if exists on_auth_user_updated on auth.users;
create trigger on_auth_user_updated
  after update on auth.users
  for each row execute procedure public.sync_auth_user_profile();

-- Backfill: ensure every existing auth user has a profile row, so no user is
-- left without a profile even if the trigger was added later. Idempotent.
insert into public.profiles (id, email, display_name)
select
  u.id,
  u.email,
  coalesce(u.raw_user_meta_data ->> 'display_name', split_part(coalesce(u.email, ''), '@', 1))
from auth.users u
on conflict (id) do update
set email = excluded.email;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

