-- Note: auth.users is created automatically by Supabase Auth.
-- profiles references auth.users(id) and holds the app user details.

create table if not exists public.classes (
  id bigint generated by default as identity primary key,
  name text not null unique,
  student_count integer not null default 0,
  updated_at timestamptz not null default now()
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  display_name text not null default '',
  role text not null default 'Chưa duyệt',
  assigned_class text,
  updated_at timestamptz not null default now()
);

-- Fix tables created by the OLD schema (create table if not exists does NOT
-- update the default of an existing table).
alter table public.profiles alter column role set default 'Chưa duyệt';

-- Auto-create a profile whenever an auth user is created
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email, display_name)
  values (
    new.id,
    new.email,
    coalesce(new.raw_user_meta_data ->> 'display_name', split_part(new.email, '@', 1))
  );
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

create table if not exists public.registrations (
  id uuid primary key default gen_random_uuid(),
  class_name text not null,
  date date not null,
  meal_type text not null,
  count integer not null default 0,
  registered_by text,
  registered_by_id uuid,
  updated_at timestamptz not null default now(),
  unique (class_name, date, meal_type)
);

create table if not exists public.announcements (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  content text not null,
  created_at timestamptz not null default now(),
  created_by text,
  created_by_id uuid,
  read_by text[] not null default '{}'
);

create table if not exists public.audit_logs (
  id uuid primary key default gen_random_uuid(),
  timestamp timestamptz not null default now(),
  user_id uuid,
  user_name text,
  action text not null,
  details jsonb
);

create table if not exists public.archived_registrations (
  id uuid primary key default gen_random_uuid(),
  class_name text not null,
  date date not null,
  meal_type text not null,
  count integer not null default 0,
  registered_by text,
  registered_by_id uuid,
  updated_at timestamptz
);

-- ============================================
-- Auth / Role helper functions (security definer to avoid RLS recursion)
-- ============================================

create or replace function public.current_user_role()
returns text
language sql
security definer
set search_path = public
stable
as $$
  select role from public.profiles where id = auth.uid();
$$;

create or replace function public.current_user_assigned_class()
returns text
language sql
security definer
set search_path = public
stable
as $$
  select assigned_class from public.profiles where id = auth.uid();
$$;

create or replace function public.is_admin()
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select coalesce((select role from public.profiles where id = auth.uid()), '') = 'Admin';
$$;

create or replace function public.is_bgh()
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select coalesce((select role from public.profiles where id = auth.uid()), '') = 'Ban Giám hiệu';
$$;

create or replace function public.is_kt_cd()
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select coalesce((select role from public.profiles where id = auth.uid()), '') = 'KT & CD';
$$;

-- Prevent non-admins from changing permission-relevant profile fields.
-- Users may update their own display_name (e.g. via signUp) but never role,
-- assigned_class or email.
create or replace function public.guard_profile_update()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if (new.id <> auth.uid()) and (not public.is_admin()) then
    raise exception 'Permission denied: cannot edit this profile';
  end if;
  if not public.is_admin() and (
    new.role is distinct from old.role
    or new.assigned_class is distinct from old.assigned_class
    or new.email is distinct from old.email
  ) then
    raise exception 'Permission denied: cannot change role, class or email';
  end if;
  return new;
end;
$$;

drop trigger if exists on_profiles_update_guard on public.profiles;
create trigger on_profiles_update_guard
  before update on public.profiles
  for each row execute procedure public.guard_profile_update();

-- Prevent non-admin/BGH users from editing announcements title/content.
-- Non-privileged users may only mark announcements as read (append own id).
create or replace function public.guard_announcement_update()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if public.is_admin() or public.is_bgh() then
    return new;
  end if;
  -- Only allow appending the current user's id to read_by; block all else.
  if (
    new.title is distinct from old.title
    or new.content is distinct from old.content
    or new.created_by is distinct from old.created_by
    or new.created_by_id is distinct from old.created_by_id
  ) then
    raise exception 'Permission denied: cannot edit announcement';
  end if;
  if new.read_by is distinct from old.read_by then
    if array_length(new.read_by, 1) > array_length(old.read_by, 1) then
      new.read_by := (select array_agg(distinct x order by x) from unnest(new.read_by) x);
    else
      raise exception 'Permission denied: cannot remove read status';
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists on_announcements_update_guard on public.announcements;
create trigger on_announcements_update_guard
  before update on public.announcements
  for each row execute procedure public.guard_announcement_update();

